import {writeFileSync} from 'node:fs';

const version = '48.0.0';
const url = `https://raw.githubusercontent.com/unicode-org/cldr-json/${version}/cldr-json/cldr-core/supplemental/currencyData.json`;
const response = await fetch(url);
if (!response.ok) throw new Error(`CLDR download failed: ${response.status}`);
const {supplemental: {currencyData: {fractions, region}}} = await response.json();
const codes = new Set(Object.keys(fractions).filter(code => code !== 'DEFAULT'));
for (const history of Object.values(region)) {
  for (const currencies of history) {
    for (const code of Object.keys(currencies)) codes.add(code);
  }
}
const rows = [...codes].sort().map(code => {
  const digits = Number(fractions[code]?._digits ?? fractions.DEFAULT._digits);
  if (!/^[A-Z]{3}$/.test(code) || !Number.isInteger(digits) || digits < 0 || digits > 20) {
    throw new Error(`Invalid currency metadata: ${code} ${digits}`);
  }
  return `    ("${code}", ${digits}),`;
});
writeFileSync(new URL('../../avenger-format-number/src/currency_data.rs', import.meta.url),
  `// Generated by tools/format-reference/generate-currencies.mjs from CLDR ${version}.\n// ${url}\n// Includes historical and common-use codes. Uses standard fraction digits, not cash rounding.\npub(crate) const CURRENCY_FRACTION_DIGITS: &[(&str, u8)] = &[\n${rows.join('\n')}\n];\n`);
console.log(`Generated ${rows.length} currency entries from CLDR ${version}.`);
